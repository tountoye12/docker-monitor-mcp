from mcp.server.fastmcp import FastMCP
from services import docker_service
from storage import database

from datetime import datetime, timezone

from config.thresholds import MONITORING_STALE_AFTER
from config import thresholds

def register_tools(mcp: FastMCP):

    @mcp.tool()
    def list_containers(include_stopped: bool = True) -> list[dict]:
        """
        List Docker containers, including stopped containers by default.
        """
        return docker_service.list_containers(include_stopped)

    @mcp.tool()
    def get_container_logs(container_name: str, lines: int = 50) -> str:
        """
        Get logs of a specific Docker container.
        """
        return docker_service.get_container_logs(container_name, lines)
    
    @mcp.tool()
    def check_container_health(container_name: str) -> dict:
        """
        Check the health status of a specific Docker container.
        """
        return docker_service.check_container_health(container_name)

    @mcp.tool()
    def get_container_stats(container_name: str) -> dict:
        """
        Get CPU, memory, and network statistics of a specific Docker container.
        """
        return docker_service.get_container_stats(container_name)

    @mcp.tool()
    def detect_errors(container_name: str, lines: int = 100) -> dict:
        """
        Analyze recent logs of a Docker container for errors and warnings.
        """
        return docker_service.detect_errors(container_name, lines)

    @mcp.tool()
    def get_infrastructure_report() -> dict:
        """
        Retrieve the latest infrastructure monitoring report
        generated by the proactive monitoring scheduler.

        Includes container health, CPU and memory utilization,
        restart activity, log errors and overall severity.
        """
        report = database.get_latest_report()

        if report is None:
            return {
                "error": "No monitoring report available."
            }

        return report

    @mcp.tool()
    def get_monitoring_summary() -> dict:
        """
        Retrieve a concise summary of the latest infrastructure
        monitoring cycle, including container counts by severity
        and the report completion timestamp.
        """

        report = database.get_latest_report()

        if report is None:
            return {
                "error": "No monitoring report available."
            }

        return {
            "completed_at": report["completed_at"],
            "duration_seconds": report["duration_seconds"],
            "summary": report["summary"]
        }


    @mcp.tool()
    def get_active_incidents() -> dict:
        """
        Retrieve currently active infrastructure incidents.

        Returns warning and critical incidents detected by
        the monitoring scheduler, with critical incidents first.
        """

        incidents = database.get_active_incidents()

        return {
            "total_active_incidents": len(incidents),
            "incidents": incidents
        }

    @mcp.tool()
    def get_incident_history(limit: int = 50) -> dict:
        """
        Retrieve recent infrastructure incident lifecycle events.

        Includes opened, escalated, deescalated and resolved
        incidents, ordered from newest to oldest.

        Args:
            limit: Number of events to retrieve (1-1000).
        """

        if not 1 <= limit <= 1000:
            return {
                "error": "Limit must be between 1 and 1000."
            }

        history = database.get_incident_history(limit)

        return {
            "total_events": len(history),
            "events": history
        }

    @mcp.tool()
    def get_monitoring_status() -> dict:
        """
        Determine whether infrastructure monitoring data
        is fresh, stale or unavailable.
        """

        report = database.get_latest_report()

        if report is None:
            return {
                "status": "unavailable",
                "message": "No monitoring report available."
            }

        completed_at = datetime.fromisoformat(
            report["completed_at"]
        )

        current_time = datetime.now(timezone.utc)

        age_seconds = (
            current_time - completed_at
        ).total_seconds()

        if age_seconds < 0:
            status = "unknown"
        elif age_seconds > MONITORING_STALE_AFTER:
            status = "stale"
        else:
            status = "fresh"

        return {
            "status": status,
            "last_completed_at": report["completed_at"],
            "age_seconds": round(age_seconds, 2),
            "stale_after_seconds": MONITORING_STALE_AFTER
        }

    @mcp.tool()
    def get_monitoring_thresholds() -> dict:
        """
        Retrieve configured infrastructure monitoring thresholds
        for CPU, memory, container restarts and log errors.

        Also includes monitoring interval and data freshness policy.
        """

        return {
            "cpu": {
                "warning": thresholds.CPU_WARNING,
                "critical": thresholds.CPU_CRITICAL,
                "unit": "percent"
            },
            "memory": {
                "warning": thresholds.MEMORY_WARNING,
                "critical": thresholds.MEMORY_CRITICAL,
                "unit": "percent"
            },
            "restarts": {
                "warning": thresholds.RESTART_WARNING,
                "critical": thresholds.RESTART_CRITICAL,
                "unit": "count"
            },
            "errors": {
                "warning": thresholds.ERROR_WARNING,
                "critical": thresholds.ERROR_CRITICAL,
                "unit": "count"
            },
            "monitoring": {
                "interval_seconds": thresholds.MONITORING_INTERVAL,
                "stale_after_seconds": thresholds.MONITORING_STALE_AFTER
            }
        }


    @mcp.tool()
    def get_container_diagnostics(container_name: str) -> dict:
        """
        Retrieve the latest stored diagnostic information
        for a specific Docker container.

        Includes health, resource utilization, log evaluations,
        overall severity and active incidents.

        Args:
            container_name: Docker container name.
        """

        report = database.get_latest_report()

        if report is None:
            return {
                "error": "No monitoring report available."
            }

        for container in report["containers"]:

            if container["name"] == container_name:

                incidents = database.get_active_incidents()

                container_incidents = [
                    incident
                    for incident in incidents
                    if incident["container_id"] == container["id"]
                ]

                return {
                    "container_name": container_name,
                    "completed_at": report["completed_at"],
                    "diagnostics": container,
                    "total_active_incidents": len(container_incidents),
                    "active_incidents": container_incidents
                }

        return {
            "error": (
                f"Container '{container_name}' not found "
                "in the latest monitoring report."
            )
        }